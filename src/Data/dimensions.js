  export const getDimensionsData = (type, model) => {
    const typeData = dimensionsData[type];
    if (!typeData) return null;
    
    if (typeData.variants) {
      const variant = typeData.variants.find(v => 
        v.data.some(row => row.model.includes(model))
      );
      return variant ? { ...typeData, ...variant } : null;
    }
    
    return typeData;
  };
  
  export const getModelDimensions = (type, model) => {
    const typeData = dimensionsData[type];
    if (!typeData) return null;
    
    if (typeData.variants) {
      for (const variant of typeData.variants) {
        const modelData = variant.data.find(row => row.model.includes(model));
        if (modelData) return { variant, modelData };
      }
    } else {
      const modelData = typeData.data.find(row => row.model.includes(model));
      if (modelData) return { variant: null, modelData };
    }
    
    return null;
  };