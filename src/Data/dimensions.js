  export const getDimensionsData = (type, model) => {
    const typeData = dimensionsData[type];
    if (!typeData) return null;
    
    if (typeData.variants) {
    const matches = typeData.variants.filter(v => 
      v.data.some(row => {
        const rowModel = String(row.model || '');
        const needle = String(model || '');
        return rowModel.includes(needle) || needle.includes(rowModel);
      })
    );
    // v.data.some(row => row.model.includes(model))  );
    if (matches.length === 0) return null;
    // Prefer NBR2 for NBR when both variants match
    const preferred = (type === 'NBR') ? (matches.find(v => v.name === 'NBR2') || matches[0]) : matches[0];
    return { ...typeData, ...preferred };
    }
    
    return typeData;
  };
  
  export const getModelDimensions = (type, model) => {
    const typeData = dimensionsData[type];
    if (!typeData) return null;
    
    if (typeData.variants) {
    const matches = typeData.variants
      .map(variant => ({ variant, modelData: variant.data.find(row => row.model.includes(model)) }))
      .filter(x => !!x.modelData);
    if (matches.length === 0) return null;
    // Prefer NBR2 for NBR
    const preferred = (type === 'NBR') ? (matches.find(x => x.variant.name === 'NBR2') || matches[0]) : matches[0];
    return preferred;
    } else {
      const modelData = typeData.data.find(row => row.model.includes(model));
      if (modelData) return { variant: null, modelData };
    }
    
    return null;
  };